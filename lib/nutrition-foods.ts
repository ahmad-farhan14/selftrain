export function findNutritionFood(name: string): NutritionFood | undefined {
  const normalizedName = name.trim().toLocaleLowerCase();
  return nutritionFoods.find((food) =>
    food.name.id.toLocaleLowerCase() === normalizedName
    || food.name.en.toLocaleLowerCase() === normalizedName
    || food.id === normalizedName,
  );
}

export function scaleNutrition(value: number, quantity: number): number {
  return Math.round(value * quantity * 10) / 10;
}
